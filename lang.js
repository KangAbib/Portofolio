let currentLang = localStorage.getItem("portfolio_lang") || "en";

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("portfolio_lang", lang);
  
  // Update all elements with data-translate attribute
  document.querySelectorAll("[data-translate]").forEach(el => {
    const key = el.getAttribute("data-translate");
    if (translations[lang] && translations[lang][key]) {
      if (key === "footer_copyright") {
        el.innerHTML = translations[lang][key];
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });

  // Update navbar active state if toggle button matches
  const toggleBtnText = document.getElementById("currentLangText");
  if (toggleBtnText) {
    toggleBtnText.textContent = lang.toUpperCase();
  }
  
  // Update document html lang attribute
  document.documentElement.lang = lang;
}

// Initial setup on DOM load
document.addEventListener("DOMContentLoaded", () => {
  setLanguage(currentLang);
  
  const switcher = document.getElementById("langSwitcher");
  if (switcher) {
    switcher.addEventListener("click", () => {
      const nextLang = currentLang === "en" ? "id" : "en";
      setLanguage(nextLang);
    });
  }
});
